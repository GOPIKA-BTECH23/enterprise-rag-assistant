<#
.SYNOPSIS
    Deploys the backend to a Hugging Face Space (Docker SDK).

.DESCRIPTION
    Builds a clean temporary folder containing only what the Space needs (Dockerfile,
    .dockerignore, backend/, data/, requirements.txt) plus a generated README.md carrying the
    Space's YAML front matter, commits it, and force-pushes it to the given git remote.
    Your GitHub README.md is never modified. backend/.env, *.db and __pycache__ are excluded.

    PDFs and .docx files are tracked with Git LFS, which Hugging Face requires for binary files.

.PARAMETER RemoteUrl
    The Space's git URL, e.g. https://huggingface.co/spaces/<hf-user>/<space-name>
    Git will ask for credentials: username = your HF username, password = an HF access
    token with *write* permission. (You can also embed them:
    https://<hf-user>:<hf-token>@huggingface.co/spaces/<hf-user>/<space-name>)

.PARAMETER Branch
    Branch to push to (default: main).

.PARAMETER DryRun
    Build and commit the folder but don't push. The folder is kept so you can inspect it.

.EXAMPLE
    .\scripts\deploy_hf_space.ps1 -RemoteUrl https://huggingface.co/spaces/GOPIKA-BTECH23/enterprise-rag-assistant
#>
[CmdletBinding()]
param(
    [Parameter(Mandatory = $true)][string]$RemoteUrl,
    [string]$Branch = "main",
    [string]$Title = "Enterprise RAG Assistant",
    [switch]$DryRun
)

$ErrorActionPreference = "Stop"

function Invoke-Git {
    param([string[]]$GitArgs, [string]$Description)
    # Native stderr (git progress output) must not be treated as a terminating error
    $prev = $ErrorActionPreference
    $ErrorActionPreference = "Continue"
    & git @GitArgs
    $code = $LASTEXITCODE
    $ErrorActionPreference = $prev
    if ($code -ne 0) { throw "git $Description failed (exit code $code)" }
}

$repoRoot = Split-Path -Parent $PSScriptRoot
$safeUrl = $RemoteUrl -replace "://[^/@]+@", "://***@"   # never print tokens
$stage = Join-Path ([IO.Path]::GetTempPath()) ("hf-space-" + [guid]::NewGuid().ToString("N").Substring(0, 8))

# ---------- Preconditions ----------
& git lfs version *> $null
if ($LASTEXITCODE -ne 0) {
    throw "Git LFS is required (Hugging Face rejects binary files without it). Install it from https://git-lfs.com and run 'git lfs install'."
}
foreach ($item in @("Dockerfile", ".dockerignore", "requirements.txt", "backend", "data")) {
    if (-not (Test-Path (Join-Path $repoRoot $item))) { throw "Missing $item in $repoRoot" }
}

try {
    # ---------- Stage files ----------
    Write-Host "Staging Space files in $stage"
    New-Item -ItemType Directory -Path $stage | Out-Null
    foreach ($item in @("Dockerfile", ".dockerignore", "requirements.txt", "backend", "data")) {
        Copy-Item -Path (Join-Path $repoRoot $item) -Destination $stage -Recurse
    }

    # Remove anything that must not be published
    Get-ChildItem -Path $stage -Recurse -Force |
        Where-Object { $_.Name -eq ".env" -or $_.Name -eq "__pycache__" -or $_.Extension -in @(".db", ".pyc", ".log") } |
        Sort-Object { $_.FullName.Length } -Descending |
        ForEach-Object { Remove-Item -LiteralPath $_.FullName -Recurse -Force }

    if (Get-ChildItem -Path $stage -Recurse -Force -Filter ".env") {
        throw "Refusing to deploy: a .env file is still present in the staging folder."
    }

    # Space README with YAML front matter (written as UTF-8 without BOM)
    $brain = [char]::ConvertFromUtf32(0x1F9E0)
    $readme = @"
---
title: $Title
emoji: $brain
colorFrom: indigo
colorTo: purple
sdk: docker
app_port: 7860
pinned: false
license: mit
short_description: Role-aware RAG API - FastAPI, FAISS and Groq
---

# $Title (backend)

FastAPI backend for the Enterprise RAG Assistant: role-based retrieval over company policy
documents with FAISS, answers generated by an LLM via Groq, with source citations and
confidence scores.

- Health check: ``/health``
- Interactive API docs: ``/docs``

This Space is generated by ``scripts/deploy_hf_space.ps1``; edit the source repository instead.

Required Space secrets: ``GROQ_API_KEY``, ``JWT_SECRET``, ``CORS_ORIGINS``.
"@
    $utf8NoBom = New-Object System.Text.UTF8Encoding $false
    [IO.File]::WriteAllText((Join-Path $stage "README.md"), $readme, $utf8NoBom)

    $gitattributes = @"
*.pdf filter=lfs diff=lfs merge=lfs -text
*.docx filter=lfs diff=lfs merge=lfs -text
*.doc filter=lfs diff=lfs merge=lfs -text
*.png filter=lfs diff=lfs merge=lfs -text
*.jpg filter=lfs diff=lfs merge=lfs -text
"@
    [IO.File]::WriteAllText((Join-Path $stage ".gitattributes"), $gitattributes, $utf8NoBom)

    # ---------- Commit ----------
    Push-Location $stage
    try {
        Invoke-Git @("init", "--quiet") "init"
        Invoke-Git @("symbolic-ref", "HEAD", "refs/heads/$Branch") "set branch"
        # Commit with LF line endings regardless of the machine's global autocrlf setting
        Invoke-Git @("config", "core.autocrlf", "input") "config"
        Invoke-Git @("config", "core.safecrlf", "false") "config"
        Invoke-Git @("lfs", "install", "--local") "lfs install"
        Invoke-Git @("add", "-A") "add"

        $identity = @()
        if (-not (& git config user.email)) { $identity = @("-c", "user.name=deploy-script", "-c", "user.email=deploy@localhost") }
        $ErrorActionPreference = "Continue"
        $sourceRev = & git -C $repoRoot rev-parse --short HEAD 2>$null
        if ($LASTEXITCODE -ne 0 -or -not $sourceRev) { $sourceRev = "local working copy" }
        $ErrorActionPreference = "Stop"
        $message = "Deploy backend ($sourceRev, $(Get-Date -Format 'yyyy-MM-dd HH:mm'))"
        Invoke-Git ($identity + @("commit", "--quiet", "-m", $message)) "commit"

        Write-Host ""
        Write-Host "Files to deploy:"
        & git ls-files | ForEach-Object { Write-Host "  $_" }
        Write-Host "LFS-tracked:"
        & git lfs ls-files | ForEach-Object { Write-Host "  $_" }

        if ($DryRun) {
            Write-Host ""
            Write-Host "Dry run: nothing pushed. Staging folder kept at $stage" -ForegroundColor Yellow
            return
        }

        # ---------- Push ----------
        Write-Host ""
        Write-Host "Force-pushing to $safeUrl ($Branch)..."
        Invoke-Git @("push", "--force", $RemoteUrl, "HEAD:refs/heads/$Branch") "push to $safeUrl"
        Write-Host "Deployed. The Space will now rebuild; watch progress in its Logs tab." -ForegroundColor Green
    }
    finally {
        Pop-Location
    }
}
finally {
    if (-not $DryRun -and (Test-Path $stage)) { Remove-Item -LiteralPath $stage -Recurse -Force }
}
